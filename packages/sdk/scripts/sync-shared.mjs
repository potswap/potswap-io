// Copies the pure modules the SDK shares with the web app so the package has no
// runtime dependency on ../app. Run `npm run sync-shared` after changing them.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const app = resolve(here, '../../../app/src')
const dest = resolve(here, '../src/shared')
mkdirSync(dest, { recursive: true })
const files = [
  ['lib/types.ts', 'lib-types.ts', {}],
  ['lib/errors.ts', 'errors.ts', { "'./types'": "'./lib-types.js'" }],
  ['terminal/types.ts', 'types.ts', {}],
  ['terminal/risk.ts', 'risk.ts', { "'./types'": "'./types.js'" }],
  ['lib/fee.ts', 'fee.ts', {}],
  ['observations/schema.ts', 'observation-schema.ts', {}],
  ['points/claims.ts', 'claims.ts', {}],
  ['points/rewards.ts', 'rewards.ts', {}],
]
for (const [from, to, rewrites] of files) {
  let src = readFileSync(resolve(app, from), 'utf8')
  for (const [a, b] of Object.entries(rewrites)) src = src.replaceAll(a, b)
  writeFileSync(resolve(dest, to), `// GENERATED by scripts/sync-shared.mjs from app/src/${from}. Do not edit here.\n${src}`)
  console.log('synced', from, '->', to)
}
